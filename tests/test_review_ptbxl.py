def test_scp_code_counts(root, tmp_path):
    res = rp.review(root, tmp_path / "out")
    c = res["counts"].set_index("code")
    assert c.loc["NORM", "n_ecgs"] == 1 and c.loc["NORM", "n_lik_100"] == 1
    assert c.loc["SR", "n_lik_0"] == 1
    assert c.loc["IMI", "n_lik_50_99"] == 1 and c.loc["IMI", "n_patients"] == 1
    assert res["mi_codes"] == ["AMI", "IMI", "INJAS"]
    assert bool(c.loc["INJAS", "kw_injury"])
    assert res["basics"]["distinct patient_id"] == 3
    assert res["basics"]["ECGs with empty scp_codes"] == 1      # kept as-is, never non-MI (L1)


def test_stadium_table(root, tmp_path):
    st = rp.review(root, tmp_path / "out")["stadium"]
    anym = st[st["code"] == "ANY_LISTED_MI_OR_INJURY_CODE"]
    assert anym["n_ecgs"].sum() == 2
    assert set(anym["infarction_stadium1"]) == {"Stadium I", "Stadium III"}
    assert st.loc[st["code"] == "ALL_ECGS", "n_ecgs"].sum() == 4


def test_early_stadium_table(root, tmp_path):
    st = rp.review(root, tmp_path / "out")["stages"].set_index("selection")["n_ecgs"]
    assert st["any listed MI/injury code"] == 2
    assert st["any listed code AND stadium1 or stadium2 in ['Stadium I', 'Stadium I-II']"] == 1
    assert st["early stadium WITHOUT any listed code"] == 0
    assert st[[k for k in st.index if k.startswith("any INJ* code (")][0]] == 1


def test_outputs_and_headers(root, tmp_path):
    out = tmp_path / "out"
    res = rp.review(root, out)
    for f in ["ptb_xl_scp_counts.csv", "ptb_xl_mi_by_stadium.csv", "ptb_xl_field_counts.csv",
              "ptb_xl_headers.csv", "ptb_xl_summary.md"]:
        assert (out / f).exists()
    h = res["headers"].iloc[0]
    assert h["fs"] == 500 and h["duration_s"] == 10 and h["units"] == "mV"
    assert "Local observation" in (out / "ptb_xl_summary.md").read_text()


def test_missing_column_reported_not_found(root, tmp_path):
    db = pd.read_csv(root / "ptbxl_database.csv").drop(columns=["second_opinion",
                                                                "infarction_stadium1",
                                                                "infarction_stadium2"])
    db.to_csv(root / "ptbxl_database.csv", index=False)
    res = rp.review(root, tmp_path / "out")
    f = res["fields"]
    assert f.loc[f["field"] == "second_opinion", "value"].tolist() == ["not found"]
    assert "not found" in res["stadium"]["note"].iloc[0]


def test_scp_codes_literal_only():
    assert rp.parse_scp_codes("{'A': 1}") == {"A": 1.0}
    with pytest.raises(ValueError):
        rp.parse_scp_codes("__import__('os')")
