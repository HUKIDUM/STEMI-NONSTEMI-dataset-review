"""PTB-XL 1.0.3 metadata review (step S3). Reads CSVs and .hea text only.

    .venv/bin/python -I src/stemi/review/review_ptbxl.py data/samples/ptb_xl

Outputs (results/):
    ptb_xl_scp_counts.csv     every SCP code: scp_statements.csv fields, keyword flags,
                              ECGs, patients, ECGs per likelihood band
    ptb_xl_mi_by_stadium.csv  MI-class / injury codes x infarction_stadium1 x _2
    ptb_xl_mi_early_stadium.csv  ECGs/patients with listed codes and stadium I or I-II
    ptb_xl_field_counts.csv   value counts of labelling, device, site, sex, stadium fields
    ptb_xl_headers.csv        one row per downloaded records500 header
    ptb_xl_summary.md
A column missing from the file is reported as "not found", never filled in.
"""

from __future__ import annotations

if __package__ in (None, ""):          # run as a file under ``python -I``
    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import argparse
import ast
from pathlib import Path

import pandas as pd

from stemi.review.common import (
    RESULTS_DIR, keyword_flags, md_table, provenance, read_text_csv, write_summary,
)
from stemi.review.hea_parser import header_row, parse_header

DATASET_ID = "ptb_xl"
RELEASE = "1.0.3 (records500)"
SCRIPT = "src/stemi/review/review_ptbxl.py"

FIELD_COLUMNS = ["validated_by_human", "initial_autogenerated_report", "second_opinion",
                 "validated_by", "device", "site", "sex", "nurse",
                 "infarction_stadium1", "infarction_stadium2", "strat_fold"]
STADIUM = ["infarction_stadium1", "infarction_stadium2"]
# Stadium values as they appear in the file. Their meaning ("acut, early" etc.) is
# documented in the paper, not here; the table only lists ECGs for review (L2, L3).
EARLY_STADIUM = ("Stadium I", "Stadium I-II")
MISSING = "<missing>"


def parse_scp_codes(s) -> dict[str, float]:
    """``"{'NORM': 100.0, 'SR': 0.0}"`` -> dict. Literal parsing only (no eval)."""
    if pd.isna(s) or not str(s).strip():
        return {}
    d = ast.literal_eval(str(s))
    if not isinstance(d, dict):
        raise ValueError(f"scp_codes is not a dict: {s!r}")
    return {str(k): float(v) for k, v in d.items()}


def explode_codes(db: pd.DataFrame) -> pd.DataFrame:
    """One row per (ECG, code, likelihood)."""
    rows = [(ecg, pat, code, lik)
            for ecg, pat, s in zip(db["ecg_id"], db["patient_id"], db["scp_codes"])
            for code, lik in parse_scp_codes(s).items()]
    return pd.DataFrame(rows, columns=["ecg_id", "patient_id", "code", "likelihood"])


def load_statements(path: Path) -> pd.DataFrame:
    st = read_text_csv(path, index_col=0)
    st.index = st.index.astype(str)
    st.index.name = "code"
    return st


def scp_counts(long: pd.DataFrame, st: pd.DataFrame) -> pd.DataFrame:
    lik = long["likelihood"]
    long = long.assign(b100=lik == 100, b50=(lik >= 50) & (lik < 100),
                       b1=(lik > 0) & (lik < 50), b0=lik == 0)
    g = long.groupby("code")
    out = pd.DataFrame({
        "n_ecgs": g["ecg_id"].nunique(),
        "n_patients": g["patient_id"].nunique(),
        "n_lik_100": g["b100"].sum(), "n_lik_50_99": g["b50"].sum(),
        "n_lik_1_49": g["b1"].sum(), "n_lik_0": g["b0"].sum(),
    })
    out = out.reindex(out.index.union(st.index)).fillna(0).astype(int)   # codes with 0 ECGs too
    out.index.name = "code"
    keep = [c for c in ["description", "diagnostic", "form", "rhythm", "diagnostic_class",
                        "diagnostic_subclass", "Statement Category",
                        "SCP-ECG Statement Description", "AHA code"] if c in st.columns]
    out = out.join(st[keep])
    out["in_scp_statements"] = out.index.isin(st.index)
    text = out.get("description", pd.Series("", index=out.index)).fillna("").astype(str)
    if "SCP-ECG Statement Description" in out.columns:
        text = text + " " + out["SCP-ECG Statement Description"].fillna("").astype(str)
    flags = pd.DataFrame([keyword_flags(t) for t in text], index=out.index)
    out = out.join(flags)
    out["diag_class_MI"] = (out.get("diagnostic_class", pd.Series(index=out.index)) == "MI")
    return out.reset_index().sort_values(["diag_class_MI", "n_ecgs"], ascending=[False, False])


def mi_codes(counts: pd.DataFrame) -> list[str]:
    """Codes listed for MI review: diagnostic_class MI, or 'injury'/'infarct' in the text."""
    m = counts["diag_class_MI"] | counts["kw_injury"] | counts["kw_infarct"]
    return sorted(counts.loc[m, "code"])


def mi_by_stadium(db: pd.DataFrame, long: pd.DataFrame, codes: list[str]) -> pd.DataFrame:
    present = [c for c in STADIUM if c in db.columns]
    if not present:
        return pd.DataFrame({"note": ["infarction_stadium columns not found in ptbxl_database.csv"]})
    stad = db.set_index("ecg_id")[present].fillna(MISSING).astype(str)
    sel = long[long["code"].isin(codes)][["ecg_id", "code"]].drop_duplicates()
    any_mi = sel[["ecg_id"]].drop_duplicates().assign(code="ANY_LISTED_MI_OR_INJURY_CODE")
    all_ecg = db[["ecg_id"]].assign(code="ALL_ECGS")
    rows = pd.concat([sel, any_mi, all_ecg]).join(stad, on="ecg_id")
    return (rows.groupby(["code"] + present).size().rename("n_ecgs").reset_index()
            .sort_values(["code", "n_ecgs"], ascending=[True, False]))


def stage_table(db: pd.DataFrame, long: pd.DataFrame, codes: list[str]) -> pd.DataFrame:
    """ECG / patient counts for listed MI codes by early stadium (listing only)."""
    present = [c for c in STADIUM if c in db.columns]
    if not present:
        return pd.DataFrame({"note": ["infarction_stadium columns not found"]})
    early = db[present].isin(EARLY_STADIUM).any(axis=1)
    has_mi = db["ecg_id"].isin(long.loc[long["code"].isin(codes), "ecg_id"])
    inj = [c for c in codes if c.startswith("INJ")]
    has_inj = db["ecg_id"].isin(long.loc[long["code"].isin(inj), "ecg_id"])
    lik100 = db["ecg_id"].isin(long.loc[long["code"].isin(codes) & (long["likelihood"] == 100), "ecg_id"])
    sets = {
        "any listed MI/injury code": has_mi,
        f"any listed code AND stadium1 or stadium2 in {list(EARLY_STADIUM)}": has_mi & early,
        f"any listed code at likelihood 100 AND early stadium": lik100 & early,
        f"early stadium WITHOUT any listed code": early & ~has_mi,
        f"any INJ* code ({', '.join(inj)})": has_inj,
        "any INJ* code AND early stadium": has_inj & early,
    }
    return pd.DataFrame([{"selection": k, "n_ecgs": int(m.sum()),
                          "n_patients": int(db.loc[m, "patient_id"].nunique())}
                         for k, m in sets.items()])


def field_counts(db: pd.DataFrame) -> pd.DataFrame:
    parts = []
    for col in FIELD_COLUMNS:
        if col not in db.columns:
            parts.append(pd.DataFrame({"field": [col], "value": ["not found"], "n_ecgs": [None]}))
            continue
        vc = db[col].fillna(MISSING).astype(str).value_counts()
        parts.append(pd.DataFrame({"field": col, "value": vc.index, "n_ecgs": vc.to_numpy()}))
    return pd.concat(parts, ignore_index=True)


def header_table(root: Path) -> pd.DataFrame:
    files = sorted((root / "records500").glob("*/*_hr.hea"))
    rows = [{"file": p.relative_to(root).as_posix(), **header_row(parse_header(p))} for p in files]
    return pd.DataFrame(rows)


def review(root: Path, out_dir: Path = RESULTS_DIR) -> dict:
    db_path, st_path = root / "ptbxl_database.csv", root / "scp_statements.csv"
    db = read_text_csv(db_path)
    st = load_statements(st_path)
    long = explode_codes(db)
    counts = scp_counts(long, st)
    codes = mi_codes(counts)
    stadium = mi_by_stadium(db, long, codes)
    stages = stage_table(db, long, codes)
    fields = field_counts(db)
    headers = header_table(root)

    out_dir.mkdir(parents=True, exist_ok=True)
    counts.to_csv(out_dir / "ptb_xl_scp_counts.csv", index=False)
    stadium.to_csv(out_dir / "ptb_xl_mi_by_stadium.csv", index=False)
    fields.to_csv(out_dir / "ptb_xl_field_counts.csv", index=False)
    stages.to_csv(out_dir / "ptb_xl_mi_early_stadium.csv", index=False)
    headers.to_csv(out_dir / "ptb_xl_headers.csv", index=False)

    per_patient = db.groupby("patient_id").size()
    basics = {
        "ECG rows in ptbxl_database.csv": len(db),
        "distinct ecg_id": db["ecg_id"].nunique(),
        "distinct patient_id": db["patient_id"].nunique(),
        "ECGs per patient: min / median / max": f"{per_patient.min()} / {per_patient.median():g} / {per_patient.max()}",
        "patients with >1 ECG": int((per_patient > 1).sum()),
        "ECGs with empty scp_codes": int((db["scp_codes"].map(parse_scp_codes).map(len) == 0).sum()),
        "codes in scp_statements.csv": len(st),
        "codes used in scp_codes": long["code"].nunique(),
        "codes used but not in scp_statements.csv": ", ".join(sorted(set(long["code"]) - set(st.index))) or "none",
        "filename_hr all under records500/": bool(db["filename_hr"].astype(str).str.startswith("records500/").all())
        if "filename_hr" in db.columns else "not found",
    }
    if "recording_date" in db.columns:
        years = pd.to_datetime(db["recording_date"], errors="coerce").dt.year
        basics["recording_date year min / max (as stored)"] = f"{years.min():g} / {years.max():g}"
    else:
        basics["recording_date"] = "not found"
    if "age" in db.columns:
        basics["age min / median / max (as stored)"] = f"{db['age'].min():g} / {db['age'].median():g} / {db['age'].max():g}"

    mi_rows = counts[counts["code"].isin(codes)]
    mi_cols = [c for c in ["code", "description", "diagnostic_class", "diagnostic_subclass",
                           "n_ecgs", "n_patients", "n_lik_100", "n_lik_50_99", "n_lik_1_49",
                           "n_lik_0", "kw_infarct", "kw_injury"] if c in mi_rows.columns]
    any_mi = long[long["code"].isin(codes)]
    hdr_note = (md_table(headers.drop(columns=["base_time", "base_date"], errors="ignore"))
                if len(headers) else "No records500 headers found under the sample folder.")
    sections = [
        ("Basic counts", md_table(pd.DataFrame(list(basics.items()), columns=["item", "value"]))),
        ("MI-related SCP codes (listed for review only; L2: not STEMI/NSTEMI labels)",
         "Selection: scp_statements.csv diagnostic_class == 'MI', or 'infarct'/'injury' in the "
         "statement text. ECGs with any listed code: "
         f"{any_mi['ecg_id'].nunique()}; patients: {any_mi['patient_id'].nunique()}; "
         f"with any listed code at likelihood 100: {any_mi.loc[any_mi['likelihood'] == 100, 'ecg_id'].nunique()}.\n\n"
         + md_table(mi_rows[mi_cols])),
        ("Listed MI/injury codes x infarction stadium (see ptb_xl_mi_by_stadium.csv)",
         md_table(stadium[stadium["code"] == "ANY_LISTED_MI_OR_INJURY_CODE"])
         if "code" in stadium.columns else md_table(stadium)),
        (f"Early-stadium listing (values {list(EARLY_STADIUM)} as stored; review only, not acute labels)",
         md_table(stages)),
        ("Labelling / device / site fields (see ptb_xl_field_counts.csv)",
         md_table(fields[fields["field"].isin(["validated_by_human", "initial_autogenerated_report",
                                               "second_opinion", "device"])])
         + f"\n\nDistinct `site` values: {db['site'].nunique() if 'site' in db.columns else 'not found'}; "
           f"distinct `validated_by` values: {db['validated_by'].nunique() if 'validated_by' in db.columns else 'not found'}."),
        (f"Headers ({len(headers)} seeded-sample files; not a release-level fact, E2)", hdr_note),
    ]
    inputs = provenance([db_path, st_path])
    write_summary(out_dir / "ptb_xl_summary.md", "PTB-XL metadata review (local observation)",
                  DATASET_ID, RELEASE, SCRIPT, inputs, sections)
    return {"counts": counts, "stadium": stadium, "stages": stages, "fields": fields, "headers": headers,
            "mi_codes": codes, "basics": basics}


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("root", type=Path, help="data/samples/ptb_xl")
    ap.add_argument("--out-dir", type=Path, default=RESULTS_DIR)
    args = ap.parse_args(argv)
    res = review(args.root, args.out_dir)
    for k, v in res["basics"].items():
        print(f"{k}: {v}")
    print(f"listed MI/injury codes: {res['mi_codes']}")


if __name__ == "__main__":
    main()
