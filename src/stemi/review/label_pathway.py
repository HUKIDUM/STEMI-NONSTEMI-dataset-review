def verified_row_keys(path: Path = VERIFIED) -> set[str]:
    keys = set()
    for ln in path.read_text().splitlines():
        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
        if len(cells) >= 6 and cells[0] not in ("Dataset", "---"):
            keys.add(f"{cells[0]} | {cells[1]}")
    return keys


def _texts(*keys: str) -> tuple[dict, list[str]]:
    out, used = {f: "" for f in TEXT_FIELDS}, []
    for k in keys:
        for f, (txt, row) in TEXT[k].items():
            out[f] = f"{out[f]}; {txt}" if out[f] else txt        # later keys add to a field
            if row not in used:
                used.append(row)
    return out, used


def _row(ds, cls, codes, count, ctype, keys, hv="", ag=""):
    txt, used = _texts(*keys)
    return {"dataset": ds, "class": cls, "source_codes": codes, "count": count, "count_type": ctype, **txt,
            "human_validated_n": hv, "autogenerated_n": ag, "source_rows": " ; ".join(used)}


def build(samples: Path = SAMPLES, out_dir: Path = RESULTS_DIR, s: lc.Sources | None = None) -> pd.DataFrame:
    s = s or lc.Sources(samples)
    db = read_text_csv(samples / "ptb_xl" / "ptbxl_database.csv").set_index("ecg_id")
    vh, ag = _true(db["validated_by_human"]), _true(db["initial_autogenerated_report"])
    rows = []
    for label, m in {**lc.MAPPING, **EXTRA_CLASSES}.items():
        if m.get("ptb_xl"):
            ids = pd.Index(s.ptbxl_long.loc[s.ptbxl_long["code"].isin(m["ptb_xl"]), "ecg_id"].unique())
            rows.append(_row("ptb_xl", label, "+".join(m["ptb_xl"]), lc.cell_ptb_xl(s, m["ptb_xl"]),
                             lc.COUNT_TYPE["ptb_xl"], ["ptb_xl"],
                             int(vh.reindex(ids).sum()), int(ag.reindex(ids).sum())))
        if m.get("ptb_diagnostic"):
            desc = "; ".join(f"{k} {op} {'/'.join(v)}" for k, op, v in m["ptb_diagnostic"])
            rows.append(_row("ptb_diagnostic", label, desc, lc.cell_ptbdb(s, m["ptb_diagnostic"]),
                             lc.COUNT_TYPE["ptb_diagnostic"], ["ptb_diagnostic"]))
        if m.get("sph"):
            rows.append(_row("sph", label, "+".join(m["sph"]), lc.cell_sph(s, m["sph"]),
                             lc.COUNT_TYPE["sph"], ["sph"]))
        if m.get("challenge"):
            for ds in CHALLENGE_IDS:
                pub, g1 = lc.cell_challenge(s, ds, m["challenge"])
                if pub == lc.NOT_PRESENT:
                    continue
                key = "challenge_cn" if ds in ("chapman_shaoxing", "ningbo") else "challenge_cg"
                keys = [key] + (["ningbo_extra"] if ds == "ningbo" and label in ("MI (any)",) else [])
                rows.append(_row(ds, label, "+".join(m["challenge"]), pub,
                                 f"{lc.COUNT_TYPE[ds]}; g1 sample union = {g1}", keys))
        if m.get("code15"):
            keys = ["code15_normal"] if m["code15"] == ["normal_ecg"] else ["code15"]
            rows.append(_row("code15", label, "+".join(m["code15"]), lc.cell_code15(s, m["code15"]),
                             lc.COUNT_TYPE["code15"], keys))
        if m.get("incart"):
            kinds = {"dx" if k.startswith("dx") else "rec" for k, _ in m["incart"]}
            rows.append(_row("incart", label, " | ".join(f"{k}: {x}" for k, x in m["incart"]),
                             lc.cell_incart(s, m["incart"]), lc.COUNT_TYPE["incart"],
                             ["incart_dx" if kinds == {"dx"} else "incart_rec"]))
    for cls, codes in MIMIC_GROUPS:
        rows.append(_row("mimic_iv_ecg", cls, codes, MIMIC_ICD_COUNT,
                         "not checked", ["mimic_icd"]))
    rows.append(_row("mimic_iv_ecg", "machine report statements (all classes)", "report_0..report_17",
                     "not checked", "not checked (machine_measurements.csv not downloaded)", ["mimic_machine"]))
    df = pd.DataFrame(rows, columns=COLUMNS)
    out_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_dir / "label_provenance.csv", index=False)
    return df


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-dir", type=Path, default=RESULTS_DIR)
    args = ap.parse_args(argv)
    df = build(out_dir=args.out_dir)
    print(df[["dataset", "class", "count", "human_validated_n", "autogenerated_n"]].to_string(index=False))


if __name__ == "__main__":
    main()
