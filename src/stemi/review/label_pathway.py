def _row(ds, cls, codes, t, n_ecgs, n_pat, ctype, hv="", ag="", **over):
    t = {**t, **over}
    return {"dataset": ds, "class": cls, "codes": codes, "ecg_recorded_where": t.get("where", ""),
            "pathway": t["pathway"], "label_from_stage": t["stage"], "labeller": t["labeller"],
            "basis": t["basis"], "timing": t["timing"], "n_ecgs": n_ecgs, "n_patients": n_pat,
            "count_type": ctype, "human_validated_n": hv, "autogenerated_n": ag, "source": t["source"]}


def build(samples: Path = SAMPLES, out_dir: Path = RESULTS_DIR, s: Sources | None = None) -> pd.DataFrame:
    s = s or Sources(samples)
    db = read_text_csv(samples / "ptb_xl" / "ptbxl_database.csv").set_index("ecg_id")
    vh, ag = _true(db["validated_by_human"]), _true(db["initial_autogenerated_report"])
    pts_of = {r: p for p, rs in zip(s.incart_pts["patient"], s.incart_pts["records"]) for r in rs}
    rows = []
    for label, m in MAPPING.items():
        if m.get("ptb_xl"):
            ids = pd.Index(s.ptbxl_long.loc[s.ptbxl_long["code"].isin(m["ptb_xl"]), "ecg_id"].unique())
            rows.append(_row("ptb_xl", label, "+".join(m["ptb_xl"]), TEXT["ptb_xl"], len(ids),
                             db.loc[ids, "patient_id"].nunique(), "records (any likelihood)",
                             int(vh.reindex(ids).sum()), int(ag.reindex(ids).sum())))
        if m.get("sph"):
            L, mask = s.sph_long, pd.Series(False, index=s.sph_long.index)
            for c in m["sph"]:
                code, _, mod = c.partition("+")
                mask |= (L["code"] == code) & ((L["modifier"] == mod) if mod else True)
            rows.append(_row("sph", label, "+".join(m["sph"]), TEXT["sph"], L.loc[mask, "ecg"].nunique(),
                             L.loc[mask, "patient"].nunique(), "records"))
        if m.get("code15"):
            hit = s.code15[m["code15"]].apply(_true).any(axis=1)
            t = TEXT["code15"] if m["code15"] != ["normal_ecg"] else {**TEXT["code15"], **TEXT["code15_normal"]}
            rows.append(_row("code15", label, "+".join(m["code15"]), t, int(hit.sum()),
                             s.code15.loc[hit, "patient_id"].nunique(), "records (exams)"))
        if m.get("challenge"):
            dm = s.dm[s.dm["SNOMEDCTCode"].isin(m["challenge"])].drop_duplicates("SNOMEDCTCode")
            for ds in CHALLENGE_IDS:
                n = int(dm[MAP_COUNT_COLUMNS[ds]].sum())
                g = s.g1[ds]
                g1 = g.loc[g["code"].isin(m["challenge"]), "record_name"].nunique()
                key = "challenge_cn" if ds in ("chapman_shaoxing", "ningbo") else "challenge_cg"
                rows.append(_row(ds, label, "+".join(m["challenge"]), TEXT[key], n, "not available",
                                 f"publisher's count as listed (sum of codes{', may double-count' if len(dm) > 1 else ''}); "
                                 f"g1 sample union = {g1}"))
        if m.get("ptb_diagnostic"):
            rec, mask = s.ptbdb, pd.Series(False, index=s.ptbdb.index)
            for key, op, values in m["ptb_diagnostic"]:
                col = rec[f"c:{key}"].fillna(KEY_MISSING)
                mask |= col.isin(values) if op == "in" else ~col.isin(values)
            desc = "; ".join(f"{k} {op} {'/'.join(v)}" for k, op, v in m["ptb_diagnostic"])
            rows.append(_row("ptb_diagnostic", label, desc, TEXT["ptb_diagnostic"], int(mask.sum()),
                             rec.loc[mask, "patient"].nunique(), "records"))
        if m.get("incart"):
            recs, kinds = set(), set()
            for kind, text in m["incart"]:
                kinds.add("dx" if kind.startswith("dx") else "rec")
                if kind in ("dx", "dx_term"):
                    P = s.incart_pts
                    hit = (P["dx"] == text) if kind == "dx" else P["dx"].str.split(",").map(
                        lambda xs: text in [x.strip() for x in xs])
                    for r in P.loc[hit, "records"]:
                        recs |= set(r)
                else:
                    T = s.incart_terms
                    hit = (T["term"] == text) if kind == "rec" else T["term"].str.contains(text, regex=False)
                    recs |= set(T.loc[hit, "record"])
            t = TEXT["incart_dx"] if kinds == {"dx"} else TEXT["incart_rec"]
            rows.append(_row("incart", label, " | ".join(f"{k}: {x}" for k, x in m["incart"]), t, len(recs),
                             len({pts_of[r] for r in recs if r in pts_of}), "records"))
    for cls, codes in MIMIC_GROUPS:
        rows.append(_row("mimic_iv_ecg", cls, codes, TEXT["mimic_icd"],
                         "pending user-run count (credentialed)", "pending user-run count (credentialed)",
                         "not checked by the team (user runs src/stemi/review/mimic_ext_icd_count.py)"))
    rows.append(_row("mimic_iv_ecg", "machine report statements (all classes)", "report_0..report_17",
                     {**TEXT["mimic_icd"], "pathway": "ECG recorded → ★ machine statement 'generated by the "
                      "ECG machine' (machine_measurements.csv)", "stage": "★ ECG-machine report text",
                      "labeller": "ECG machine", "basis": "ECG only", "timing": "this ECG"},
                     "not checked", "not checked", "not checked (machine_measurements.csv not downloaded)"))
    df = pd.DataFrame(rows, columns=COLUMNS)
    out_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_dir / "label_provenance.csv", index=False)
    return df


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-dir", type=Path, default=RESULTS_DIR)
    args = ap.parse_args(argv)
    df = build(out_dir=args.out_dir)
    print(df[["dataset", "class", "n_ecgs", "n_patients", "human_validated_n", "autogenerated_n"]]
          .to_string(index=False))


if __name__ == "__main__":
    main()
