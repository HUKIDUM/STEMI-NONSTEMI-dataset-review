ICD_GROUPS = [
    ("I21.0-I21.3", r"I21[0-3]\w*"),
    ("I21.4", r"I214\w*"),
    ("I21.9 / I21.A*", r"I21(9|A)\w*"),
    ("I22.*", r"I22\w*"),
    ("I25.2", r"I252\w*"),
]


def _codes_in_cell(v) -> list[str]:
    """A cell may hold one code or a list ("['I214', 'I10']" or "I214;I10")."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return []
    t = str(v).strip()
    if t.startswith("["):
        try:
            items = ast.literal_eval(t)
        except (ValueError, SyntaxError):
            items = re.split(r"[,\s;]+", t.strip("[]"))
    else:
        items = re.split(r"[,;|\s]+", t)
    return [re.sub(r"[^A-Z0-9]", "", str(x).upper()) for x in items if str(x).strip(" '\"")]


def _suppress(n: int) -> str:
    return "<10" if n < SUPPRESS_BELOW else str(int(n))


def mimic_icd_group_counts(df: pd.DataFrame, *, ecg_col: str = "study_id",
                           patient_col: str = "subject_id", code_col: str = "all_diag_all",
                           source_col: str | None = None) -> pd.DataFrame:
    """Aggregate ECGs/patients per ICD-10 group, optionally split by a diagnosis-source column.

    Defaults follow the Ext-ICD Data Description column names (study_id, subject_id,
    all_diag_all; https://physionet.org/content/mimic-iv-ecg-ext-icd-labels/1.0.1/). The value
    format of the diag columns is NOT documented: the parser is tolerant (format assumed).
    NOT run by the team. Output holds no IDs or dates;
    every count < 10 prints as "<10". A code matching no group is ignored.
    """
    long = df[[ecg_col, patient_col, code_col] + ([source_col] if source_col else [])].copy()
    long["code"] = long[code_col].map(_codes_in_cell)
    long = long.explode("code").dropna(subset=["code"])
    rows = []
    sources = [None] + (sorted(long[source_col].dropna().astype(str).unique()) if source_col else [])
    for src in sources:
        part = long if src is None else long[long[source_col].astype(str) == src]
        for name, pat in ICD_GROUPS:
            hit = part[part["code"].str.fullmatch(pat)]
            rows.append({"icd_group": name, "diagnosis_source": "all" if src is None else src,
                         "ecgs": _suppress(hit[ecg_col].nunique()),
                         "patients": _suppress(hit[patient_col].nunique())})
    return pd.DataFrame(rows)


