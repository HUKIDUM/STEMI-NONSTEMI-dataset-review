import pandas as pd

from stemi.review.common import RESULTS_DIR, read_text_csv
from stemi.review.label_crosswalk import MAPPING, PTBXL_MI
from stemi.review.review_ptbxl import explode_codes, load_statements

SAMPLES = Path(__file__).resolve().parents[3] / "data" / "samples"
PROV_COLUMNS = ("validated_by_human", "second_opinion", "initial_autogenerated_report", "validated_by")
EXTRA_SCOPE = ["STE_", "STD_", "NST_", "ISC_", "ISCAL", "ISCIN", "ISCIL", "ISCAS", "ISCLA", "ISCAN"]
SUPPRESS_BELOW = 10


def ptbxl_scope() -> list[str]:
    """All MI codes, STE_/STD_/NST_, ISC*, and every PTB-XL code behind the 21 crosswalk labels."""
    codes = list(PTBXL_MI) + EXTRA_SCOPE
    for m in MAPPING.values():
        codes += m.get("ptb_xl", [])
    return sorted(set(codes))


def _bool(s: pd.Series) -> pd.Series:
    return s.astype(str).str.strip().str.lower().isin({"true", "1"})


def ptbxl_provenance(db: pd.DataFrame, scope: list[str], st: pd.DataFrame | None = None) -> pd.DataFrame:
    missing = [c for c in PROV_COLUMNS if c not in db.columns]
    if missing:
        raise KeyError(f"provenance columns not found in ptbxl_database.csv: {missing}")
    long = explode_codes(db)
    flags = db.set_index("ecg_id")
    vh = _bool(flags["validated_by_human"])
    so = _bool(flags["second_opinion"])
    ag = _bool(flags["initial_autogenerated_report"])
    vb = flags["validated_by"].notna() & (flags["validated_by"].astype(str).str.strip() != "")
    rows = []
    for code in scope:
        ecgs = pd.Index(long.loc[long["code"] == code, "ecg_id"].unique())
        sub = lambda m: int(m.reindex(ecgs).sum())                     # noqa: E731
        rows.append({
            "code": code,
            "description": st.loc[code, "description"] if st is not None and code in st.index else "",
            "n_ecgs": len(ecgs),
            "n_patients": int(flags.loc[ecgs, "patient_id"].nunique()) if len(ecgs) else 0,
            "validated_by_human_true": sub(vh), "validated_by_human_false": sub(~vh),
            "second_opinion_true": sub(so),
            "initial_autogenerated_report_true": sub(ag),
            "autogenerated_and_not_validated_by_human": sub(ag & ~vh),
            "validated_by_filled": sub(vb),
            "n_ecgs_likelihood_100": int(long.loc[(long["code"] == code) & (long["likelihood"] == 100),
                                                  "ecg_id"].nunique()),
        })
    return pd.DataFrame(rows)


def ptbxl_patterns(db: pd.DataFrame) -> dict:
    """Observations only (no causes): validated x autogenerated crosstab, and codes that never
    occur on an autogenerated ECG."""
    vh, ag = _bool(db["validated_by_human"]), _bool(db["initial_autogenerated_report"])
    xt = pd.crosstab(vh.rename("validated_by_human"), ag.rename("initial_autogenerated_report"))
    long = explode_codes(db)
    ag_ids = set(db.loc[ag, "ecg_id"])
    never = sorted(c for c, g in long.groupby("code") if not set(g["ecg_id"]) & ag_ids)
    return {"crosstab": xt, "never_autogenerated": never,
            "nonvalidated_subset_of_autogenerated": int((~vh & ~ag).sum()) == 0,
            "autogenerated_then_validated": int((vh & ag).sum())}


def code15_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Every column with its values type; flags the documented label columns. No origin column
    is assumed: `origin_column_found` says whether any column name refers to label origin."""
    label_cols = {"1dAVb", "RBBB", "LBBB", "SB", "ST", "AF", "normal_ecg"}
    origin_pat = re.compile(r"origin|source|annot|label|review|cardiolog|auto|manual", re.I)
    rows = []
    for c in df.columns:
        vals = set(df[c].dropna().astype(str).str.lower().unique()[:5])
        rows.append({"column": c, "is_label_column": c in label_cols,
                     "looks_boolean": bool(vals) and vals <= {"true", "false"},
                     "name_refers_to_origin": bool(origin_pat.search(c)),
                     "n_true": int(_bool(df[c]).sum()) if c in label_cols else ""})
    out = pd.DataFrame(rows)
    out["origin_column_found"] = bool(out["name_refers_to_origin"].any())
    return out


