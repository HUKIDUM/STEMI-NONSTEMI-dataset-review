"""Label provenance counts (task S13, part S2). Uses only files already in data/samples/.

    .venv/bin/python -I src/stemi/review/label_provenance.py

- PTB-XL: per SCP code in scope, ECGs by human validation / second opinion / auto-generated
  report. Column names are checked against the file header; a missing one is reported,
  never assumed.
- CODE-15%: label columns, and whether any column records label origin (listed, not guessed).
- MIMIC: `mimic_icd_group_counts()` is written and tested on synthetic data only. It is NOT
  run here: the MIMIC diagnosis file is not read until the user approves it, and its column
  names stay parameters until planner confirms the documented schema.
Outputs: results/label_provenance_counts_ptb_xl.csv, results/label_provenance_counts_code15.csv
"""

