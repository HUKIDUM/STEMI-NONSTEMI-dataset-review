def build(samples: Path = SAMPLES, out_dir: Path = RESULTS_DIR) -> dict:
    db = read_text_csv(samples / "ptb_xl" / "ptbxl_database.csv")
    st = load_statements(samples / "ptb_xl" / "scp_statements.csv")
    ptb = ptbxl_provenance(db, ptbxl_scope(), st)
    c15 = code15_columns(read_text_csv(samples / "code15" / "exams.csv"))
    out_dir.mkdir(parents=True, exist_ok=True)
    ptb.to_csv(out_dir / "label_provenance_counts_ptb_xl.csv", index=False)
    c15.to_csv(out_dir / "label_provenance_counts_code15.csv", index=False)
    pat = ptbxl_patterns(db)
    xt = pat["crosstab"]
    text = ["# Label provenance counts: summary (local observation of the downloaded files)", "",
            f"- PTB-XL: `results/label_provenance_counts_ptb_xl.csv`, {len(ptb)} SCP codes in scope "
            "(MI codes, STE_/STD_/NST_, ISC*, and the codes behind the 21 crosswalk labels).",
            "- CODE-15%: `results/label_provenance_counts_code15.csv`; no column records label origin "
            f"(origin_column_found = {bool(c15['origin_column_found'].any())}).", "",
            "## PTB-XL whole file: validated_by_human x initial_autogenerated_report (ECGs)", "",
            "| validated_by_human | autogenerated False | autogenerated True |", "|---|---|---|",
            *[f"| {i} | {xt.loc[i, False] if False in xt.columns else 0} | "
              f"{xt.loc[i, True] if True in xt.columns else 0} |" for i in xt.index], "",
            "Observation: every ECG with validated_by_human = False has an autogenerated initial report "
            "(non-validated ⊂ autogenerated; " + ("holds" if pat["nonvalidated_subset_of_autogenerated"]
                                                    else "does NOT hold") +
            f"), but {pat['autogenerated_then_validated']:,} autogenerated ECGs are human-validated, "
            "so the two sets are not equal.", "",
            f"Observation only (no cause is stated by any source): {len(pat['never_autogenerated'])} codes "
            "never occur on an autogenerated ECG: " + ", ".join(pat["never_autogenerated"]) + ".", ""]
    (out_dir / "label_provenance_counts_summary.md").write_text("\n".join(text))
    return {"ptb_xl": ptb, "code15": c15, "patterns": pat}


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-dir", type=Path, default=RESULTS_DIR)
    args = ap.parse_args(argv)
    res = build(out_dir=args.out_dir)
    print(res["ptb_xl"].to_string(index=False))
    print(res["code15"].to_string(index=False))


if __name__ == "__main__":
    main()
